export function labelFor(value: string): string {
  switch (value) {
    case 'PreparedFood': return HUNGER_COPY.categories.PreparedFood;
    case 'Groceries': return HUNGER_COPY.categories.Groceries;
    case 'Stationery': return HUNGER_COPY.categories.Stationery;
    case 'Donor': return HUNGER_COPY.roles.donor;
    case 'Recipient': return HUNGER_COPY.roles.recipient;
    case 'Admin': return HUNGER_COPY.roles.admin;
    case 'Available': return HUNGER_COPY.donationStatus.Available;
    case 'Requested': return HUNGER_COPY.donationStatus.Requested;
    case 'Accepted': return HUNGER_COPY.donationStatus.Accepted;
    case 'PickedUp': return HUNGER_COPY.donationStatus.PickedUp;
    case 'Delivered': return HUNGER_COPY.donationStatus.Delivered;
    case 'Cancelled': return HUNGER_COPY.donationStatus.Cancelled;
    case 'Pending': return HUNGER_COPY.reviewStatus.Pending;
    case 'Approved': return HUNGER_COPY.reviewStatus.Approved;
    case 'Rejected': return HUNGER_COPY.reviewStatus.Rejected;
    case 'PendingReview': return HUNGER_COPY.contributionStatus.PendingReview;
    case 'Open': return HUNGER_COPY.needStatus.Open;
    case 'PartiallyFulfilled': return HUNGER_COPY.needStatus.PartiallyFulfilled;
    case 'Fulfilled': return HUNGER_COPY.needStatus.Fulfilled;
    case 'Closed': return HUNGER_COPY.needStatus.Closed;
    default: return value;
  }
}
